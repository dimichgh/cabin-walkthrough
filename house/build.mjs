#!/usr/bin/env node
// Build the walkable cabin into ONE self-contained HTML file: dist/cabin-house.html
// (three.js, the app, the verified facts from ../data/cabin.js — all inline; no external requests).
import esbuild from 'esbuild';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '..');

// 1 · facts: reuse the verified node text from the holo model, with compass wording fixed.
//     The plan north arrow, the site plan and the building section agree: terrace = north, lake = west,
//     garage door = east. The A401 elevation titles disagree with that arrow; the model follows the arrow, so the
//     sheet titled EAST is read as the west (lake) face, and the facts say so in those words.
globalThis.window = {};
await import(pathToFileURL(path.join(root, 'data/cabin.js')).href);
const A = globalThis.window.HOLO_ARCH;
const fix = (s) => typeof s !== 'string' ? s : s
  .replace(/\bon the east elevation\b/g, 'on the elevation titled EAST')
  .replace(/\bon the west elevation\b/g, 'on the elevation titled WEST (the entry face in this model)')
  .replace(/\bThe east elevation\b/g, 'The elevation titled EAST (the lake face in this model)')
  .replace(/\bthe east elevation\b/g, 'the elevation titled EAST (the lake face in this model)')
  .replace(/\bThe west elevation\b/g, 'The elevation titled WEST')
  .replace(/\bthe west elevation\b/g, 'the elevation titled WEST')
  .replace(/\bEast band\b/g, 'Ribbon band')
  .replace(/\bon the west roof\b/g, 'on the roof');
const INFO = {};
for (const n of A.nodes) INFO[n.id] = { name: fix(n.name), tagline: fix(n.tagline), role: fix(n.role), why: fix(n.why), facts: (n.facts || []).map(fix), where: n.where, status: n.status };
const STATUS = Object.fromEntries(Object.entries(A.status).map(([k, v]) => [k, { label: v.label }]));
const left = JSON.stringify(INFO).match(/\b(east|west) (elevation|band|roof)\b/gi);
if (left) console.warn('compass wording left to review:', [...new Set(left)]);
fs.writeFileSync(path.join(here, 'src/info.js'), `// generated by build.mjs from data/cabin.js — do not edit\nexport const INFO = ${JSON.stringify(INFO)};\nexport const STATUS = ${JSON.stringify(STATUS)};\n`);

// 2 · bundle
const r = await esbuild.build({ entryPoints: [path.join(here, 'src/main.js')], bundle: true, format: 'iife', minify: true, write: false, target: 'es2020', legalComments: 'none', logLevel: 'warning' });
const js = r.outputFiles[0].text.replace(/<\/script/gi, '<\\/script');

// 3 · inline + self-containment gate
let html = fs.readFileSync(path.join(here, 'index.html'), 'utf8');
html = html.replace('<!--BUNDLE-->', () => `<script>${js}</script>`);
const bad = html.match(/\b(?:src|href|action|poster)\s*=\s*["']?\s*(?:https?:)?\/\/[^"'\s>]+|url\(\s*["']?\s*(?:https?:)?\/\/[^)]+\)|@import\s+(?:url\()?["']?(?:https?:)?\/\/|\bimport\s*\(\s*["'](?:https?:)?\/\//gi);
if (bad) { console.error('✗ not self-contained:', [...new Set(bad)].slice(0, 8)); process.exit(1); }
for (const d of [path.join(here, 'dist'), path.join(root, 'dist')]) fs.mkdirSync(d, { recursive: true });
const out = path.join(here, 'dist/cabin-house.html');
fs.writeFileSync(out, html);
fs.copyFileSync(out, path.join(root, 'dist/cabin-house.html'));
const extra = process.argv.indexOf('--out');
if (extra > 0) { const f = path.resolve(process.argv[extra + 1]); fs.mkdirSync(path.dirname(f), { recursive: true }); fs.copyFileSync(out, f); console.log(`  also → ${f}`); }
console.log(`✓ ${path.relative(root, out)}  ${(html.length / 1024).toFixed(0)} KB  (copied to dist/cabin-house.html)`);
